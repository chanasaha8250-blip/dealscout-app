export function generateMockComparison(query: string): ComparisonResult[] {
  const base = mockProducts.find((p) => p.title.toLowerCase().includes(query.toLowerCase().split(' ')[0]));
  const basePrice = base?.currentPrice ?? 20000;
  const baseUrl = base?.originalStoreUrl ?? 'https://www.amazon.in/product/dp/B0CHX1W1XY';

  return [
    {
      storeName: 'Amazon',
      price: Math.round(basePrice * 1.0),
      originalPrice: Math.round(basePrice * 1.25),
      deliveryDays: 1,
      inStock: true,
      url: `${baseUrl}?ref=amazon`,
      rating: 4.5,
    },
    {
      storeName: 'Flipkart',
      price: Math.round(basePrice * 0.96),
      originalPrice: Math.round(basePrice * 1.22),
      deliveryDays: 2,
      inStock: true,
      url: 'https://www.flipkart.com/search?q=' + encodeURIComponent(query),
      rating: 4.3,
    },
    {
      storeName: 'Croma',
      price: Math.round(basePrice * 1.03),
      originalPrice: Math.round(basePrice * 1.30),
      deliveryDays: 3,
      inStock: true,
      url: 'https://www.croma.com/search?q=' + encodeURIComponent(query),
      rating: 4.4,
    },
  ];
}
